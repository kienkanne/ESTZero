// gen_golden; regenerates the frozen oracle-golden test data.
//
// For each golden system it replicates wfn.cc::get_energy exactly, dumping every
// intermediate quantity (S/T/V/ERI, densities, J/K, orbitals, MO integrals, and
// scf/mp2 energies) to tests/golden/data/<name>.golden. Before freezing, it
// cross-checks the scf and mp2 energies against the Psi4 oracle in
// bench/reference.json and ABORTS if either drifts by more than 1e-6, so data
// can never be frozen from code that has diverged from the oracle.
//
// This is a developer tool, not part of the test suite. Run it manually after a
// deliberate, benchmark-confirmed change and commit the updated .golden files.

#include <fstream>
#include <sstream>
#include <iostream>
#include <regex>
#include <string>
#include <cmath>

#include <Eigen/Dense>

#include "wfn.h"
#include "utils.h"
#include "build_JK.h"
#include "rhf.h"
#include "uhf.h"
#include "transmo.h"
#include "mp2.h"
#include "golden_io.h"

using golden::Matrix;

namespace {

constexpr double ORACLE_TOL = 1e-6;

// Minimal extractor for bench/reference.json. The file is machine-generated with
// stable formatting, so a targeted regex per (label, method) is sufficient and
// avoids pulling in a JSON library. Returns the "energy" under
// <label> -> <method> -> energy.
double read_psi4_energy(const std::string& json, const std::string& label,
                        const std::string& method) {
    // Escape regex-special chars in the label (e.g. the '/' and '**' cases).
    std::string esc;
    for (char c : label) {
        if (std::string("\\^$.|?*+()[]{}").find(c) != std::string::npos) esc += '\\';
        esc += c;
    }
    const std::string pattern =
        "\"" + esc + "\"\\s*:\\s*\\{[\\s\\S]*?\"" + method +
        "\"\\s*:\\s*\\{\\s*\"energy\"\\s*:\\s*(-?[0-9.eE+]+)";
    std::smatch m;
    if (!std::regex_search(json, m, std::regex(pattern)))
        throw std::runtime_error("gen_golden: no Psi4 " + method + " energy for " + label);
    return std::stod(m[1].str());
}

void check_oracle(const std::string& label, const std::string& method,
                  double mine, double psi4) {
    const double diff = std::abs(mine - psi4);
    std::cout << "    " << method << ": mine=" << mine << " psi4=" << psi4
              << " |d|=" << diff << (diff <= ORACLE_TOL ? "  OK" : "  DRIFT") << "\n";
    if (diff > ORACLE_TOL)
        throw std::runtime_error("gen_golden: " + label + "/" + method +
                                  " drifted from Psi4 oracle by " + std::to_string(diff) +
                                  " (> " + std::to_string(ORACLE_TOL) + "); refusing to freeze.");
}

} // namespace

int main() {
    const std::string repo = SCF_REPO_ROOT;

    // Load the Psi4 oracle once.
    std::ifstream ref_in(repo + "/bench/reference.json");
    if (!ref_in) {
        std::cerr << "gen_golden: cannot open bench/reference.json "
                     "(run bench/gen_reference.py first)\n";
        return 1;
    }

    // Convert the input stream to a string
    std::stringstream ss;
    ss << ref_in.rdbuf();
    const std::string ref_json = ss.str();

    try {
        for (const auto& sys : golden::golden_systems()) {
            std::cout << "[gen_golden] " << sys.label << " (" << sys.reference << ")\n";

            WaveFunction wfn(repo + "/" + sys.xyz, sys.basis, sys.mult, sys.charge);
            wfn.get_integrals();

            const Matrix& S = wfn.get_S();
            const Matrix& T = wfn.get_T();
            const Matrix& V = wfn.get_V();
            const std::vector<double>& eri = wfn.get_eri_vector();
            const double V_nn = wfn.get_Vnn();
            const int n_docc  = wfn.get_n_docc();
            const int n_alpha = wfn.get_n_alpha();
            const int n_beta  = wfn.get_n_beta();

            const double psi4_scf = read_psi4_energy(ref_json, sys.label, "scf");
            const double psi4_mp2 = read_psi4_energy(ref_json, sys.label, "mp2");
            
            // Format output frozen golden data to file
            std::ofstream out(golden::data_path(sys.name));
            out << "# auto-generated by gen_golden. DO NOT EDIT BY HAND\n"
                << "# oracle: Psi4 (bench/reference.json), scf/mp2 matched to " << ORACLE_TOL << "\n";
            out << "system " << sys.label << "\n";
            out << "reference " << sys.reference << "\n";
            out << "nbf " << S.rows() << "\n";
            out << "n_docc " << n_docc << "\n";
            out << "n_alpha " << n_alpha << "\n";
            out << "n_beta " << n_beta << "\n";

            golden::write_matrix(out, "S", S);
            golden::write_matrix(out, "T", T);
            golden::write_matrix(out, "V", V);
            golden::write_list(out, "eri", eri);
            golden::write_scalar(out, "v_nn", V_nn);
            golden::write_scalar(out, "psi4_scf_energy", psi4_scf);
            golden::write_scalar(out, "psi4_mp2_energy", psi4_mp2);

            if (sys.reference == "rhf") {
                // Mirrors wfn.cc / rhf.cc exactly.
                Result r = rhf_scf(1e-10, 200, 0, V_nn, n_docc, S, T, V, eri);
                Matrix C_occ = r.Ca.leftCols(n_docc);
                Matrix D = C_occ * C_occ.transpose();
                JK jk = build_JK(eri, D);
                Tensor I_mo = transform_rhf_MO(eri, r.Ca, n_docc);
                double E_mp2 = calc_rhf_MP2_E(I_mo, r.epsa, n_docc, r.E0);

                check_oracle(sys.label, "scf", r.E0, psi4_scf);
                check_oracle(sys.label, "mp2", E_mp2, psi4_mp2);

                golden::write_scalar(out, "E_scf", r.E0);
                golden::write_scalar(out, "E_mp2", E_mp2);
                golden::write_matrix(out, "D", D);
                golden::write_matrix(out, "J", jk.J);
                golden::write_matrix(out, "K", jk.K);
                golden::write_vector(out, "eps", r.epsa);
                golden::write_matrix(out, "C", r.Ca);
                golden::write_tensor4(out, "I_mo", I_mo);
            } else { // uhf
                // Mirrors wfn.cc / uhf.cc exactly.
                Result r = uhf_scf(1e-10, 200, 0, V_nn, n_alpha, n_beta, S, T, V, eri);
                Matrix Ca_occ = r.Ca.leftCols(n_alpha);
                Matrix Cb_occ = r.Cb.leftCols(n_beta);
                Matrix Da = Ca_occ * Ca_occ.transpose();
                Matrix Db = Cb_occ * Cb_occ.transpose();
                JK jka = build_JK(eri, Da);
                JK jkb = build_JK(eri, Db);
                SpinMO mo = transform_uhf_MO(eri, r.Ca, n_alpha, r.Cb, n_beta);
                double E_mp2 = calc_uhf_MP2_E(mo.Iaa_mo, mo.Ibb_mo, mo.Iab_mo,
                                              r.epsa, r.epsb, n_alpha, n_beta, r.E0);

                check_oracle(sys.label, "scf", r.E0, psi4_scf);
                check_oracle(sys.label, "mp2", E_mp2, psi4_mp2);

                golden::write_scalar(out, "E_scf", r.E0);
                golden::write_scalar(out, "E_mp2", E_mp2);
                golden::write_matrix(out, "Da", Da);
                golden::write_matrix(out, "Db", Db);
                golden::write_matrix(out, "Ja", jka.J);
                golden::write_matrix(out, "Ka", jka.K);
                golden::write_matrix(out, "Jb", jkb.J);
                golden::write_matrix(out, "Kb", jkb.K);
                golden::write_vector(out, "epsa", r.epsa);
                golden::write_vector(out, "epsb", r.epsb);
                golden::write_matrix(out, "Ca", r.Ca);
                golden::write_matrix(out, "Cb", r.Cb);
                golden::write_tensor4(out, "Iaa", mo.Iaa_mo);
                golden::write_tensor4(out, "Ibb", mo.Ibb_mo);
                golden::write_tensor4(out, "Iab", mo.Iab_mo);
            }
            std::cout << "    wrote " << golden::data_path(sys.name) << "\n";
        }
    } catch (const std::exception& e) {
        std::cerr << "[gen_golden] error: " << e.what() << "\n";
        return 1;
    }

    std::cout << "[gen_golden] done.\n";
    return 0;
}
